export async function toggleFeatured(id) {
  const product = await Product.findById(id);
  if (!product) throw ApiError.notFound('Product not found');
  product.isFeatured = !product.isFeatured;
  await product.save();
  return product;
}

// ── Stock update ────────────────────────────────────────

export async function updateStock(id, stock) {
  if (stock === undefined || stock === null || stock < 0) {
    throw ApiError.badRequest('Stock must be a non-negative number');
  }

  const product = await Product.findById(id);
  if (!product) throw ApiError.notFound('Product not found');

  product.stock = stock;

  // Auto-flip status when stock changes
  if (stock === 0 && product.status === 'active') {
    product.status = 'out_of_stock';
  } else if (stock > 0 && product.status === 'out_of_stock') {
    product.status = 'active';
  }

  await product.save();
  return product;
}

// ── Image management ────────────────────────────────────

export async function addImages(id, files) {
  if (!files || files.length === 0) {
    throw ApiError.badRequest('At least one image file is required');
  }

  const product = await Product.findById(id);
  if (!product) throw ApiError.notFound('Product not found');

  if (product.images.length + files.length > MAX_IMAGES) {
    throw ApiError.badRequest(
      `Cannot exceed ${MAX_IMAGES} images. Current: ${product.images.length}, uploading: ${files.length}.`
    );
  }

  const uploaded = await uploadImages(files);

  const isFirstImage = product.images.length === 0;
  for (let i = 0; i < uploaded.length; i += 1) {
    product.images.push({
      url: uploaded[i].url,
      publicId: uploaded[i].publicId,
      alt: '',
      isPrimary: isFirstImage && i === 0, // auto-set first image as primary
    });
  }

  await product.save();
  return product;
}

export async function removeImage(id, publicId) {
  if (!publicId) throw ApiError.badRequest('Image publicId is required');

  const product = await Product.findById(id);
  if (!product) throw ApiError.notFound('Product not found');

  const idx = product.images.findIndex((img) => img.publicId === publicId);
  if (idx === -1) throw ApiError.notFound('Image not found on this product');

  const wasPrimary = product.images[idx].isPrimary;
  product.images.splice(idx, 1);

  // If we removed the primary, auto-promote the first remaining image
  if (wasPrimary && product.images.length > 0) {
    product.images[0].isPrimary = true;
  }

  await product.save();

  // Clean up Cloudinary in background (don't block the response)
  deleteImage(publicId);

  return product;
}

export async function reorderImages(id, publicIds) {
  if (!Array.isArray(publicIds) || publicIds.length === 0) {
    throw ApiError.badRequest('publicIds array is required');
  }

  const product = await Product.findById(id);
  if (!product) throw ApiError.notFound('Product not found');

  // Build a map of existing images by publicId
  const imageMap = new Map();
  for (const img of product.images) {
    if (img.publicId) imageMap.set(img.publicId, img);
  }

  // Validate all provided publicIds exist
  for (const pid of publicIds) {
    if (!imageMap.has(pid)) {
      throw ApiError.badRequest(`Image not found: ${pid}`);
    }
  }

  // Rebuild images array in the new order
  const reordered = publicIds.map((pid) => imageMap.get(pid));

  // Append any images not in publicIds (shouldn't happen but be safe)
  for (const img of product.images) {
    if (img.publicId && !publicIds.includes(img.publicId)) {
      reordered.push(img);
    }
  }

  product.images = reordered;
  await product.save();
  return product;
}

export async function setPrimaryImage(id, publicId) {
  if (!publicId) throw ApiError.badRequest('Image publicId is required');

  const product = await Product.findById(id);
  if (!product) throw ApiError.notFound('Product not found');

  let found = false;
  for (const img of product.images) {
    if (img.publicId === publicId) {
      img.isPrimary = true;
      found = true;
    } else {
      img.isPrimary = false;
    }
  }
  if (!found) throw ApiError.notFound('Image not found on this product');

  await product.save();
  return product;
}
