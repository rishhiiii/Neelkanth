import { Product } from '../models/index.js';
import ApiError from '../utils/ApiError.js';
import { uploadImages, deleteImage, deleteImages } from './imageService.js';

const MAX_IMAGES = 8;

/**
 * Fields the `client` admin role is blocked from editing on UPDATE.
 * On CREATE, all fields are allowed (required fields like hsnCode/gstRate/sku
 * must be provided). The restriction applies only to later modifications.
 */
const CLIENT_BLOCKED_FIELDS = ['hsnCode', 'gstRate', 'sku', 'status'];

/**
 * Strip blocked fields from the update payload if the admin is a `client`.
 */
function enforceRoleRestrictions(data, role) {
  if (role === 'developer') return data;
  const filtered = { ...data };
  for (const field of CLIENT_BLOCKED_FIELDS) {
    delete filtered[field];
  }
  return filtered;
}

// ── CRUD ────────────────────────────────────────────────

export async function createProduct(data) {
  const {
    name, sku, shortDescription, description, category, healthTags, packSize,
    form, price, stock, lowStockThreshold, hsnCode, gstRate, isFeatured,
    ingredients, dosage, directions, benefits, indications, precautions,
  } = data;

  if (!name || !sku || !price || !hsnCode || !gstRate || !category) {
    throw ApiError.badRequest('name, sku, price, hsnCode, gstRate, and category are required');
  }

  const product = await Product.create({
    name, sku, shortDescription, description, category, healthTags, packSize,
    form, price, stock, lowStockThreshold, hsnCode, gstRate, isFeatured,
    ingredients, dosage, directions, benefits, indications, precautions,
    status: data.status || 'draft',
  });

  return product;
}

export async function updateProduct(id, data, role) {
  const product = await Product.findById(id);
  if (!product) throw ApiError.notFound('Product not found');

  const allowed = enforceRoleRestrictions(data, role);

  // Updatable fields (slug auto-regenerated by pre-validate hook when name changes)
  const fields = [
    'name', 'shortDescription', 'description', 'category', 'healthTags',
    'packSize', 'form', 'price', 'lowStockThreshold', 'isFeatured',
    'ingredients', 'dosage', 'directions', 'benefits', 'indications',
    'precautions', 'hsnCode', 'gstRate', 'sku', 'status',
  ];

  for (const key of fields) {
    if (allowed[key] !== undefined) {
      product[key] = allowed[key];
    }
  }

  await product.save();
  return product;
}

export async function getProductById(id) {
  const product = await Product.findById(id)
    .populate('category', 'name slug')
    .populate('healthTags', 'name slug')
    .lean();
  if (!product) throw ApiError.notFound('Product not found');
  return product;
}

/**
 * Admin product list — includes all statuses, with pagination, search, and
 * filter by category.
 *
 * Query params: page, limit, search (name/sku), category, status, featured
 */
export async function listProducts(query) {
  const page = Math.max(1, parseInt(query.page, 10) || 1);
  const limit = Math.min(50, Math.max(1, parseInt(query.limit, 10) || 20));
  const skip = (page - 1) * limit;

  const filter = {};

  if (query.search) {
    const escapeRegex = (str) => str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const re = new RegExp(escapeRegex(query.search), 'i');
    filter.$or = [{ name: re }, { sku: re }];
  }
  if (query.category) filter.category = query.category;
  if (query.status) filter.status = query.status;
  if (query.featured !== undefined) filter.isFeatured = query.featured === 'true';

  const [docs, total] = await Promise.all([
    Product.find(filter)
      .populate('category', 'name slug')
      .sort({ createdAt: -1 })
      .skip(skip)
      .limit(limit)
      .lean(),
    Product.countDocuments(filter),
  ]);

  return {
    products: docs,
    meta: { page, limit, total, pages: Math.ceil(total / limit) },
  };
}

export async function deleteProduct(id) {
  const product = await Product.findById(id);
  if (!product) throw ApiError.notFound('Product not found');
  if (product.status === 'archived') {
    throw ApiError.badRequest('Product is already archived');
  }

  product.status = 'archived';
  await product.save();
  return product;
}

